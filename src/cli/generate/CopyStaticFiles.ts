import {createId} from '#/core/Id.js'
import {generatedDatabaseFile} from '#/database/Version.js'
import fs from 'node:fs/promises'
import path from 'node:path'
import {writeFileIfContentsDiffer} from '../util/FS.js'
import type {GenerateContext} from './GenerateContext.js'

const packageJson = {
  private: true,
  version: '0.0.0',
  name: '@alinea/generated',
  type: 'module',
  sideEffects: false,
  exports: {
    './package.json': './package.json',
    './config.js': './config.js',
    './release.js': './release.js',
    [`./${generatedDatabaseFile}`]: `./${generatedDatabaseFile}`,
    './database.js': './database.js'
  }
}

export async function copyStaticFiles({outDir}: GenerateContext) {
  await fs.mkdir(outDir, {recursive: true}).catch(console.error)
  await cleanupOldDatabases(outDir)

  await fs.writeFile(
    path.join(outDir, 'release.js'),
    `export const release = ${JSON.stringify(createId())}`
  )
  await fs.writeFile(
    path.join(outDir, 'package.json'),
    JSON.stringify(packageJson, null, 2)
  )
  await fs.writeFile(
    path.join(outDir, 'database.js'),
    `export const database = undefined`
  )
  // await writeFileIfContentsDiffer(path.join(outDir, '.gitignore'), `*\n!.keep`)*/
  await writeFileIfContentsDiffer(
    path.join(outDir, '.keep'),
    '# Contents of this folder are autogenerated by alinea'
  )
}

export async function cleanupOldDatabases(outDir: string): Promise<void> {
  const files = await fs.readdir(outDir).catch(() => [])
  const currentFiles = new Set([
    generatedDatabaseFile,
    `${generatedDatabaseFile}-shm`,
    `${generatedDatabaseFile}-wal`
  ])
  const oldFiles = files.filter(
    file =>
      !currentFiles.has(file) &&
      /^database(?:-.+)?\.sqlite(?:-(?:shm|wal))?$/.test(file)
  )
  await Promise.all(
    oldFiles.map(file =>
      fs.rm(path.join(outDir, file), {force: true}).catch(() => {})
    )
  )
}
