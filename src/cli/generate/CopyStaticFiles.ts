import fs from 'node:fs/promises'
import path from 'node:path'
import {MemorySource} from '#/core/source/MemorySource.js'
import {exportSource} from '#/core/source/SourceExport.js'
import {writeFileIfContentsDiffer} from '../util/FS.js'
import type {GenerateContext} from './GenerateContext.js'

const emptySource = await exportSource(new MemorySource())

export interface GeneratedSecrets {
  releaseId: string
  configId: string
}

export async function copyStaticFiles(
  {outDir}: GenerateContext,
  secrets: GeneratedSecrets
) {
  await fs.mkdir(outDir, {recursive: true}).catch(console.error)

  await fs.writeFile(
    path.join(outDir, 'release-meta.json'),
    JSON.stringify({
      releaseId: secrets.releaseId,
      releaseUrl: '',
      configId: secrets.configId,
      configUrl: ''
    })
  )
  await fs.writeFile(
    path.join(outDir, 'replica-catalog.json'),
    JSON.stringify({
      version: 1,
      bundleId: secrets.releaseId,
      bundleUrl: '',
      revision: '',
      records: {},
      indexes: {}
    })
  )
  await fs.writeFile(
    path.join(outDir, 'replica-keys.json'),
    JSON.stringify({
      version: 1,
      bundleId: secrets.releaseId,
      revision: '',
      accessClasses: {}
    })
  )
  await fs.writeFile(
    path.join(outDir, 'source.json'),
    JSON.stringify(emptySource, null, 2)
  )
  // await writeFileIfContentsDiffer(path.join(outDir, '.gitignore'), `*\n!.keep`)*/
  await writeFileIfContentsDiffer(
    path.join(outDir, '.keep'),
    '# Contents of this folder are autogenerated by alinea'
  )
}
