import {createId} from '#/core/Id.js'
import {generatedDatabaseFile} from '#/database/Version.js'
import fs from 'node:fs/promises'
import path from 'node:path'
import type {GenerateContext} from './GenerateContext.js'

const packageJson = {
  private: true,
  version: '0.0.0',
  name: '@alinea/generated',
  type: 'module',
  sideEffects: false,
  exports: {
    './package.json': './package.json',
    './config.js': './config.js',
    './release.js': './release.js',
    [`./${generatedDatabaseFile}`]: `./${generatedDatabaseFile}`,
    './database.node.js': './database.node.js'
  }
}

export async function copyStaticFiles({outDir}: GenerateContext) {
  await fs.mkdir(outDir, {recursive: true}).catch(console.error)
  // Everything else in this folder is written again by this run, so files
  // that older Alinea versions generated do not linger. The database stays so
  // unchanged content is not indexed again.
  const keep = new Set([
    generatedDatabaseFile,
    `${generatedDatabaseFile}-shm`,
    `${generatedDatabaseFile}-wal`
  ])
  const files = await fs.readdir(outDir).catch(() => [])
  await Promise.all(
    files
      .filter(file => !keep.has(file))
      .map(file =>
        fs
          .rm(path.join(outDir, file), {recursive: true, force: true})
          .catch(() => {})
      )
  )

  await fs.writeFile(
    path.join(outDir, 'release.js'),
    `export const release = ${JSON.stringify(createId())}`
  )
  await fs.writeFile(
    path.join(outDir, 'package.json'),
    JSON.stringify(packageJson, null, 2)
  )
  // A static asset reference lets file tracing bundle the database with the
  // serverless functions that open it, wherever this package is hoisted to.
  await fs.writeFile(
    path.join(outDir, 'database.node.js'),
    `export const database = new URL(${JSON.stringify(`./${generatedDatabaseFile}`)}, import.meta.url)`
  )
  await fs.writeFile(
    path.join(outDir, '.keep'),
    '# Contents of this folder are autogenerated by alinea'
  )
}
